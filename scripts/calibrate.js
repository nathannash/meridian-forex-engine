#!/usr/bin/env node
// Offline calibration. Reads data/raw/*.csv and writes:
//   data/params/<CODE>.json   one static parameter file per country
//   data/params/assets.json   real US asset returns by year
//   src/params/index.js       the same files bundled as an ES module, so the
//                             engine loads synchronously in Node, the browser
//                             and a web worker alike
//
// Usage: node scripts/calibrate.js

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { logRealRate, fitAr1, confidenceGrade } from '../src/estimate.js';
import { percentileRank } from '../src/stats.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const raw = (f) => join(root, 'data', 'raw', f);

const DATA_STATUS = 'illustrative';
const DATA_NOTE =
  'Approximate values entered from memory; not traced to primary sources. Replace during phase 0 (data audit) before any result is shown to users.';

// Stand-in for the pooled panel estimate of phi, which needs the phase 2
// panel. A 4-year half-life is the middle of the 3-5 year range the design
// cites; the standard error spans roughly that range.
const PHI_PRIOR = {
  value: round(Math.pow(0.5, 1 / 4), 6),
  se: 0.04,
  source: 'prior: 4-year half-life placeholder for the phase 2 pooled panel estimate',
};

const meta = JSON.parse(readFileSync(raw('countries.json'), 'utf8'));
const us = readCsv(raw('US.csv'));
const usCpi = new Map(us.map((r) => [r.year, r.cpi_us]));

// Real asset returns, deflated by US CPI. The first year has no prior CPI and
// drops out.
const assets = { status: DATA_STATUS, note: DATA_NOTE, units: 'real USD, decimal', years: [], equity: [], bond: [], inflation: [] };
for (let i = 1; i < us.length; i++) {
  const infl = us[i].cpi_us / us[i - 1].cpi_us;
  assets.years.push(us[i].year);
  assets.equity.push(round((1 + us[i].equity / 100) / infl - 1, 6));
  assets.bond.push(round((1 + us[i].bond / 100) / infl - 1, 6));
  assets.inflation.push(round(infl - 1, 6));
}

const params = { assets };

for (const [code, m] of Object.entries(meta)) {
  if (m.tier === 'home') {
    params[code] = {
      code,
      ...m,
      dataStatus: DATA_STATUS,
      dataAsOf: assets.years.at(-1),
      sample: null,
      model: { q0: 0, mu: 0, phi: 0, sigma: 0, phiSe: 0, muSe: 0, halfLifeYears: 0, longRunSd: 0 },
      history: null,
      shocks: {},
      confidence: confidenceGrade({ years: Infinity }),
    };
    continue;
  }

  const rows = readCsv(raw(`${code}.csv`)).filter((r) => usCpi.has(r.year));
  const years = rows.map((r) => r.year);
  const q = logRealRate({
    S: rows.map((r) => r.S),
    cpiLocal: rows.map((r) => r.cpi_local),
    cpiUs: rows.map((r) => usCpi.get(r.year)),
  });
  const fit = fitAr1(years, q, { phiPrior: PHI_PRIOR });
  const q0 = q.at(-1);

  params[code] = {
    code,
    ...m,
    dataStatus: DATA_STATUS,
    dataNote: DATA_NOTE,
    dataAsOf: years.at(-1),
    sample: { first: years[0], last: years.at(-1), years: years.length },
    model: {
      q0: round(q0, 6),
      mu: round(fit.mu, 6),
      phi: round(fit.phi, 6),
      phiSource: fit.phiSource,
      phiOwn: round(fit.phiOwn, 6),
      phiOls: round(fit.phiOls, 6),
      sigma: round(fit.sigma, 6),
      phiSe: round(fit.phiSe, 6),
      muSe: round(fit.muSe, 6),
      halfLifeYears: round(fit.halfLifeYears, 3),
      longRunSd: round(fit.longRunSd, 6),
    },
    valuation: {
      // Where today's level sits in the country's own history: 0 = cheapest
      // year on record, 1 = most expensive.
      percentile: round(percentileRank(q, q0), 4),
      gapToLongRun: round(Math.exp(q0 - fit.mu) - 1, 4),
    },
    history: { years, q: q.map((v) => round(v, 6)) },
    shocks: Object.fromEntries(Object.entries(fit.shocks).map(([y, z]) => [y, round(z, 6)])),
    confidence: confidenceGrade({ years: years.length, regimeBreaks: m.regimeBreaks, pooled: fit.phiSource !== 'own' }),
  };
}

for (const [code, p] of Object.entries(params)) {
  writeFileSync(join(root, 'data', 'params', `${code}.json`), JSON.stringify(p, null, 2) + '\n');
}
writeFileSync(
  join(root, 'src', 'params', 'index.js'),
  '// GENERATED by scripts/calibrate.js from data/raw. Do not edit by hand.\n' +
    `export const PARAMS = ${JSON.stringify(params, null, 2)};\n`,
);

for (const [code, p] of Object.entries(params)) {
  if (code === 'assets' || p.tier === 'home') continue;
  const { model: md, sample } = p;
  console.log(
    `${code}: ${sample.first}-${sample.last} (${sample.years} yrs)  phi=${md.phi} [own: ${md.phiOwn}, OLS ${md.phiOls}]  ` +
      `half-life=${md.halfLifeYears}y  sigma=${md.sigma}  long-run sd=${md.longRunSd}  ` +
      `q0-mu=${round(md.q0 - md.mu, 4)}  grade=${p.confidence.label}`,
  );
}

function readCsv(path) {
  const lines = readFileSync(path, 'utf8')
    .split('\n')
    .filter((l) => l.trim() && !l.startsWith('#'));
  const header = lines[0].split(',');
  return lines.slice(1).map((l) => {
    const cells = l.split(',');
    return Object.fromEntries(header.map((h, i) => [h, Number(cells[i])]));
  });
}

function round(x, d) {
  const f = 10 ** d;
  return Math.round(x * f) / f;
}
